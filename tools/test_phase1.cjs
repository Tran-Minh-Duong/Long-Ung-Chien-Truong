const assert = require('node:assert/strict');
const { loadGame } = require('./game-test-runtime.cjs');

const game = loadGame();
const api = game.GAME_API;
const chat = (user, text) => api.event({ type: 'comment', user, name: user, text });
const tanks = () => Array.from(game.state.units.filter((unit) => unit.tier === 'siegeTank'), (unit) => [unit.t, unit.route]);
const tally = () => JSON.parse(JSON.stringify(game.state.siegeVote.votes));

api.newMatch();
api.startSiegeVote();
const deadline = game.state.siegeVote.endsAt;
chat('a', '1 top');
chat('a', '1 top');
assert.equal(tally()[0].top, 1);
api.startSiegeVote();
assert.equal(game.state.siegeVote.endsAt, deadline);
assert.equal(tally()[0].top, 1, 'Opening an active vote preserves its ballots');
chat('a', '2 mid');
chat('b', '1 top');
chat('c', '2 adc');
assert.deepEqual(tally(), [{ top: 1, mid: 1, bot: 0 }, { top: 0, mid: 0, bot: 1 }]);
game.state.siegeVote.endsAt = 0;
chat('too-late', '1 top');
assert.equal(tally()[0].top, 1, 'A vote at or past its deadline is ignored');
game.step(0.02);
assert.deepEqual(tanks(), [[0, 'mid'], [1, 'bot']], 'A tie favors mid, and adc selects bot');
game.step(0.02);
assert.equal(tanks().length, 2, 'A round spawns at most one tank per team');

api.newMatch();
game.state.time = 1800 - 180;
game.step(0.02);
assert.equal(game.state.siegeVote.active, true, 'An automatic vote starts at 3 minutes');
chat('voter', '1 adc');
chat('other-voter', '1 top');
game.state.siegeVote.endsAt = 0;
game.step(0.02);
assert.deepEqual(tanks(), [[0, 'top']], 'Top beats adc on a tie; no votes gives no tank');
api.jump(2);
game.step(0.02);
assert.equal(game.state.siegeVote.active, false, 'Jumping past vote times does not replay skipped rounds');
api.startOvertime();
api.startSiegeVote();
assert.equal(game.state.siegeVote.active, false, 'Overtime blocks voting');

api.newMatch();
const paidSoldier = game.spawnUnit(0, 'soldier', 'top', { id: 'donor' });
while (game.state.units.length < game.UNIT_LIMIT) game.spawnUnit(0, 'soldier', 'top', null);
api.spawnSiegeTank(9, 'mid');
api.spawnSiegeTank(0, 'bad-route');
assert.equal(game.state.siegeQueue.length, 0);
api.spawnSiegeTank(1, 'mid');
assert.equal(game.state.units.length, game.UNIT_LIMIT);
assert.equal(game.state.units[0], paidSoldier, 'A full field keeps existing troops');
assert.equal(game.state.siegeQueue.length, 1);
api.event({ type: 'gift', user: 'new-donor', name: 'New donor', giftId: 5655, giftName: 'Rose', coins: 1, count: 1 });
game.state.units[1].dead = true;
game.step(0.02);
assert.equal(game.state.siegeQueue.length, 1, 'Queued gifts take the first free slot');
for (const unit of game.state.units.slice(1, 4)) unit.dead = true;
game.step(0.02);
assert.deepEqual(tanks(), [[1, 'mid']], 'The queued tank deploys as soon as a slot is free');
assert.equal(game.state.siegeQueue.length, 0);
assert(game.state.units.includes(paidSoldier));
api.newMatch();
assert.deepEqual(tanks(), []);
assert.equal(game.state.siegeQueue.length, 0);
console.log('Phase 1 passed: real siege votes, time jumps, unit cap and gift priority.');

